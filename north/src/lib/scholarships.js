export const isSeniorsOnly = (s) => s.grades.length === 1 && s.grades[0] === 12;

export function gradeLabel(s) {
  if (s.grades.length === 4) return "Grades 9–12";
  if (isSeniorsOnly(s)) return "Seniors only";
  if (s.grades.length === 1) return s.grades[0] === 11 ? "Juniors only" : `Grade ${s.grades[0]}`;
  return `Grades ${s.grades[0]}–${s.grades[s.grades.length - 1]}`;
}

export function locationLabel(s) {
  if (s.states.length === 0) return s.rural ? "Rural students" : "Nationwide";
  return s.states.map((code) => STATE_NAMES[code] || code).join(", ");
}

/**
 * Could this student plausibly apply? Unknown profile fields never exclude.
 * Returns { ok, reasons[] } so the UI can explain why something is hidden.
 */
export function matchScholarship(s, profile) {
  const reasons = [];
  const grade = Number(profile.grade);

  if (grade >= 9 && grade <= 12 && !s.grades.includes(grade)) {
    const allowed = s.grades.some((g) => g > grade);
    reasons.push(allowed ? `Opens in ${gradeLabel(s).toLowerCase()}` : "Not for your grade");
  }

  if (profile.state && s.states.length > 0 && !s.states.includes(profile.state)) {
    reasons.push(`Only for ${locationLabel(s)}`);
  }

  const status = profile.citizenship;
  if (status) {
    const isCitizen = status === "citizen";
    const isPR = status === "permanent-resident";
    const isDaca = status === "daca";

    if (s.citizenship === "citizen" && !isCitizen) reasons.push("Requires US citizenship");
    if (s.citizenship === "citizen-pr" && !isCitizen && !isPR) reasons.push("Requires citizenship or a green card");
    if (s.citizenship === "daca" && !isCitizen && !isPR && !isDaca) reasons.push("Requires citizenship, a green card or DACA");
    if (s.citizenship === "undocumented" && (isCitizen || isPR)) reasons.push("Only for undocumented / DACA / TPS students");
  }

  return { ok: reasons.length === 0, reasons };
}

/** Months until the usual deadline (0 = this month). null when rolling. */
export function monthsUntil(s, now = new Date()) {
  if (!s.month) return null;
  return (s.month - 1 - now.getMonth() + 12) % 12;
}

